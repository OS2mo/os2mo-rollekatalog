"""Persons are removed when their IT-users expire."""

import uuid
from collections.abc import Awaitable
from collections.abc import Callable
from datetime import date
from datetime import datetime
from datetime import time
from datetime import timedelta

import pytest
from httpx import AsyncClient

from os2mo_rollekatalog.autogenerated_graphql_client import EmployeeCreateInput
from os2mo_rollekatalog.autogenerated_graphql_client import GraphQLClient
from os2mo_rollekatalog.autogenerated_graphql_client import ITUserTerminateInput


@pytest.mark.integration_test
@pytest.mark.envvar({"LISTEN_TO_CHANGES_IN_MO": "False"})
async def test_expired_ituser_removes_person(
    test_client: AsyncClient,
    graphql_client: GraphQLClient,
    trigger_event: Callable[[str, uuid.UUID], Awaitable[None]],
    root_uuid: uuid.UUID,
    create_it_system: Callable[..., Awaitable[uuid.UUID]],
    create_ituser: Callable[..., Awaitable[uuid.UUID]],
) -> None:
    """The event for an IT-user that has reached its end date removes the
    person."""
    # Arrange: a synced person whose AD account ended yesterday.
    employee = (
        await graphql_client._testing__create_employee(
            input=EmployeeCreateInput(given_name="Anders", surname="And")
        )
    ).uuid
    AD = await create_it_system("Active Directory")
    FK = await create_it_system("FK ORG")
    object_guid = uuid.uuid4()
    ad_ituser = await create_ituser(
        itsystem=AD,
        external_id=str(object_guid),
        person=employee,
        user_key="AA",
        engagements=[],
    )
    await create_ituser(
        itsystem=FK,
        external_id=str(uuid.uuid4()),
        person=employee,
        user_key=str(object_guid),
        engagements=[],
    )
    await trigger_event("ituser", ad_ituser)
    users = (await test_client.get(f"/cache/person/{employee}")).json()
    assert [user["userId"] for user in users] == ["AA"]

    yesterday = datetime.combine(date.today() - timedelta(days=1), time.min)
    await graphql_client._testing__terminate_it_user(
        input=ITUserTerminateInput(uuid=ad_ituser, to=yesterday)
    )

    # Act: the event MO sends when the end date is reached.
    await trigger_event("ituser", ad_ituser)

    # Assert.
    assert (await test_client.get(f"/cache/person/{employee}")).json() == []
